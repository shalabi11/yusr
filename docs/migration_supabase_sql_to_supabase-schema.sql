-- Remove duplicate rows before switching PK to composite key.
with ranked as (
  select ctid,
         row_number() over (
           partition by surah_number, verse_number
           order by created_at nulls last, ctid
         ) as rn
  from public.quran_verses
)
delete from public.quran_verses q
using ranked r
where q.ctid = r.ctid
  and r.rn > 1;

