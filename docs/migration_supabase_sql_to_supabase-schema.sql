begin
  if to_regclass('public.user_reminders_legacy') is not null then
    if (select count(*) from public.user_reminders) = 0 then
      insert into public.user_reminders (
        user_id,
        title,
        subtitle,
        frequency,
        weekday,
        time_of_day,
        enabled,
        icon_code_point,
        source_id,
        created_at,
        updated_at
      )
