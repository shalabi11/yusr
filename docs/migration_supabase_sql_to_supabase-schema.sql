        user_id,
        title,
        coalesce(subtitle, ''),
        case when frequency::text = 'weekly_friday' then 'weekly_friday' else 'daily' end,
        weekday,
        time_of_day,
        coalesce(enabled, true),
        coalesce(icon_code_point, 0),
        source_id,
        created_at,
        updated_at
      from public.user_reminders_legacy;
